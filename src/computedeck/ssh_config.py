"""Small, explicit OpenSSH configuration writer for cloud endpoints."""

import logging
import os
import re
import tempfile
from pathlib import Path
from typing import Any

logger = logging.getLogger("computedeck")
_ALIAS = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,190}\Z")
_HOST = re.compile(r"[A-Za-z0-9][A-Za-z0-9.:-]{0,252}\Z")
_USER = re.compile(r"[A-Za-z0-9_][A-Za-z0-9_.@-]{0,79}\Z")


def validate_alias(value: str) -> str:
    if not _ALIAS.fullmatch(value):
        raise ValueError("SSH alias allows only letters, numbers, dots, dashes or underscores")
    return value


def validate_username(value: str) -> str:
    if not _USER.fullmatch(value):
        raise ValueError("Invalid SSH username")
    return value


def validate_endpoint(instance: dict[str, Any]) -> None:
    if not _HOST.fullmatch(str(instance.get("host") or "")):
        raise ValueError("SSH host must be a hostname or an IP address, without shell syntax")
    validate_username(str(instance.get("username") or ""))
    port = instance.get("port")
    if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= 65535:
        raise ValueError("SSH port must be between 1 and 65535")
    if instance.get("identity_file"):
        quote_path(instance["identity_file"])


def quote_path(value: str | Path) -> str:
    """Quote literal paths, allowing spaces but not config/token/glob injection."""
    path = str(value)
    if not path.startswith(("/", "~/")):
        raise ValueError("SSH paths must be absolute or start with ~/")
    if any(ord(char) < 32 for char in path) or any(char in path for char in "*?[]"):
        raise ValueError("SSH paths cannot contain control characters or wildcards")
    if "${" in path:
        raise ValueError("SSH paths must be literal, without environment expansion")
    escaped = path.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    return f'"{escaped}"'


def _host_block(instance: dict[str, Any], alias: str) -> list[str]:
    if instance.get("existing_alias"):
        # The user's own Host block, including any ProxyJump, stays authoritative.
        return [f"# Uses existing SSH configuration: {alias}", ""]
    validate_endpoint(instance)
    lines = [
        f"Host {alias}",
        f"    HostName {instance['host']}",
        f"    User {instance['username']}",
        f"    Port {instance['port']}",
        "    BatchMode yes",
        "    StrictHostKeyChecking yes",
        "    ConnectTimeout 10",
    ]
    if instance.get("identity_file"):
        lines.append(f"    IdentityFile {quote_path(instance['identity_file'])}")
    return [*lines, ""]


def render_config(instances: list[dict[str, Any]], *, strict: bool = True) -> str:
    """Strict rendering rejects the whole set; otherwise invalid endpoints are skipped.

    Validation of user input is strict. Writing the file for the running service is not,
    so one bad stored row can never stop the service or hide every other endpoint.
    """
    lines = ["# Generated by ComputeDeck. Edit endpoints in the app.", ""]
    seen: set[str] = set()
    for instance in sorted(instances, key=lambda item: str(item.get("ssh_alias", ""))):
        if not instance.get("host") or not instance.get("port"):
            continue
        if instance.get("state") in {"terminated", "deleted"}:
            continue
        try:
            alias = validate_alias(str(instance.get("ssh_alias") or ""))
            if alias in seen:
                raise ValueError(f"Duplicate managed SSH alias: {alias}")
            block = _host_block(instance, alias)
        except ValueError as error:
            if strict:
                raise
            logger.warning("Skipped SSH endpoint %s: %s", instance.get("id"), error)
            continue
        seen.add(alias)
        lines.extend(block)
    # Include files share parsing scope with their caller. Restore global scope so
    # the last managed Host cannot capture the user's following global settings.
    lines.extend(["Host *", ""])
    return "\n".join(lines)


def _atomic_write(path: Path, content: str) -> None:
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="") as handle:
            handle.write(content)
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def write_config(instances: list[dict[str, Any]], data_dir: Path) -> Path:
    content = render_config(instances, strict=False)
    data_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    path = data_dir / "computedeck.conf"
    _atomic_write(path, content)
    return path


def install_config(config_path: Path, ssh_dir: Path) -> None:
    """Explicit integration action only; never called during discovery or preview."""
    if not config_path.is_file():
        raise ValueError("Generate the managed SSH configuration before installing it")
    include = f"Include {quote_path(config_path.resolve())}\n"
    ssh_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    target = ssh_dir / "config"
    if target.is_symlink():
        raise ValueError("SSH config is a symlink; add the previewed Include manually")
    original = ""
    if target.exists():
        with target.open(encoding="utf-8", newline="") as handle:
            original = handle.read()
    prefix = "# ComputeDeck managed endpoints\n" + include + "\n"
    if original.startswith(prefix):
        return
    # Earlier settings win in OpenSSH; prepend without rewriting existing bytes.
    # https://man.openbsd.org/ssh_config
    if target.exists():
        descriptor, backup = tempfile.mkstemp(prefix="config.computedeck-backup-", dir=ssh_dir)
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="") as handle:
            handle.write(original)
        Path(backup).chmod(0o600)
    _atomic_write(target, prefix + original)
