import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { tokens, contrastMore } from '../src/theme/tokens.ts';
import { cssColor, linearRGB } from '../src/theme/color.ts';

const directory = new URL('../src/theme/', import.meta.url);
for (const [name, pair] of Object.entries(tokens)) {
  for (const [theme, color] of Object.entries(pair)) {
    if (linearRGB(color).some((channel) => channel < -0.000001 || channel > 1.000001))
      throw new Error(`sRGB clipping: ${name} (${theme})`);
  }
}
const names = Object.keys(tokens);
const block = (selector, values) => `${selector} {\n${values.join('\n')}\n}\n`;
const declarations = (theme, more = false) =>
  names.map(
    (name) => `  --${name}: var(--p-${more ? (contrastMore[name] ?? name) : name}-${theme});`,
  );
const contexts = (more) =>
  block(':root', declarations('light', more)) +
  `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', declarations('dark', more))}}\n` +
  block(':root[data-theme="light"]', declarations('light', more)) +
  block(':root[data-theme="dark"]', declarations('dark', more));
let css = '/* Generated by scripts/gen-tokens.mjs. Edit tokens.ts, not this file. */\n';
css +=
  ':root { color-scheme: light dark; }\n:root[data-theme="light"] { color-scheme: light; }\n:root[data-theme="dark"] { color-scheme: dark; }\n';
css += block(
  ':root',
  names.flatMap((name) => [
    `  --p-${name}-light: ${cssColor(tokens[name].light)};`,
    `  --p-${name}-dark: ${cssColor(tokens[name].dark)};`,
  ]),
);
css += block(
  ':root',
  names.map((name) => `  --${name}: light-dark(var(--p-${name}-light), var(--p-${name}-dark));`),
);
css += `@media (prefers-contrast: more) {\n${block(
  ':root',
  names.map((name) => {
    const source = contrastMore[name] ?? name;
    return `  --${name}: light-dark(var(--p-${source}-light), var(--p-${source}-dark));`;
  }),
)}}\n`;
css += `@supports not (color: light-dark(#000, #fff)) {\n${contexts(false)}@media (prefers-contrast: more) {\n${contexts(true)}}\n}\n`;
const system = Object.fromEntries(
  names.map((name) => [
    name,
    name.startsWith('bg-') || name.endsWith('-bg') || name.startsWith('id-tint-')
      ? 'Canvas'
      : name === 'fg-on-ink'
        ? 'Canvas'
        : name === 'grid-others'
          ? 'GrayText'
          : name === 'scrim' || name === 'chart-area'
            ? 'transparent'
            : 'CanvasText',
  ]),
);
css += `@media (forced-colors: active) {\n${block(
  ':root, :root:not([data-theme="light"]), :root[data-theme="light"], :root[data-theme="dark"]',
  Object.entries(system).map(([name, value]) => `  --${name}: ${value};`),
)}}\n`;
// Renaming both the declaration function and the feature query exercises the real fallback.
const fallback = css.replaceAll('light-dark(', 'unsupported-light-dark(');
for (const [name, value] of [
  ['tokens.css', css],
  ['tokens.fallback-only.css', fallback],
]) {
  const path = new URL(name, directory);
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== value) throw new Error(`Regenerate ${fileURLToPath(path)}`);
  } else writeFileSync(path, value);
}
